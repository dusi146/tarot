// Build one pasteable Apps Script file, with the same prompts and card catalogue.
const fs = require('node:fs');
const path = require('node:path');
const root = path.resolve(__dirname, '..');
const read = file => fs.readFileSync(path.join(root, file), 'utf8');
const output = '// Generated by node tools/build-apps-script.cjs. No API key belongs in this file.\n'
  + 'var TarotServerPersona = (function () { var module = { exports: {} };\n'
  + read('tarot-persona.js') + '\nreturn module.exports; })();\n'
  + 'var TarotServerCards = (function () { var window = {};\n'
  + read('tarot-data.js') + '\nreturn window.TAROT_CARDS; })();\n'
  + read('apps-script/backend.js');
fs.writeFileSync(path.join(root, 'apps-script/Code.gs'), output, 'utf8');
console.log('Built apps-script/Code.gs (no credentials).');
